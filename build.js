#!/usr/bin/env node
// Collects every problem in the problems/ folder into problems.generated.js,
// which the page loads. GitHub runs this automatically on each commit (see
// .github/workflows/deploy.yml). Run it yourself to preview the site locally:
//
//   node build.js
//
// Layout:
//   problems/<set folder>/set.txt     optional: title, rules, type, columns, note
//   problems/<set folder>/<name>.txt  one problem per file
// Folders and files are shown in name order (numbers sort naturally, so
// 2 comes before 10).
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, 'problems');
const byName = (a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });

function lines(file) {
  return fs.readFileSync(file, 'utf8').split(/\r?\n/).map((l) => l.trim())
    .filter((l) => l && !l.startsWith('//'));
}

// "03-quantifier-negation" -> "Quantifier Negation"
function titleFromFolder(name) {
  const words = name.replace(/^\d+[\s._-]*/, '').replace(/[-_]+/g, ' ').trim();
  return words ? words.replace(/\b\w/g, (c) => c.toUpperCase()) : name;
}

// Problem files: any .txt except set.txt; README and other files are ignored.
const problemFiles = (dir) => fs.readdirSync(dir, { withFileTypes: true })
  .filter((e) => e.isFile() && /\.txt$/i.test(e.name) && e.name.toLowerCase() !== 'set.txt')
  .map((e) => e.name).sort(byName);

// Returns the problems in the text format logic.js reads ("# Title",
// "rules: ...", then one problem per line).
// `where`, if given, is filled with problem line -> file it came from.
function collect(root = ROOT, where = new Map()) {
  const out = [];
  const add = (file) => lines(file).forEach((l) => {
    out.push(l);
    if (!where.has(l)) where.set(l, path.relative(__dirname, file));
  });
  if (!fs.existsSync(root)) return '';

  const loose = problemFiles(root);
  if (loose.length) {
    out.push('# Problems');
    loose.forEach((f) => add(path.join(root, f)));
  }

  const folders = fs.readdirSync(root, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('.')).map((e) => e.name).sort(byName);
  for (const folder of folders) {
    const dir = path.join(root, folder);
    const setFile = path.join(dir, 'set.txt');
    const settings = fs.existsSync(setFile) ? lines(setFile) : [];
    const titleLine = settings.find((l) => /^title\s*:/i.test(l));
    const title = titleLine ? titleLine.replace(/^title\s*:/i, '').trim() : titleFromFolder(folder);
    out.push('', '# ' + title);
    out.push(...settings.filter((l) => l !== titleLine));
    problemFiles(dir).forEach((f) => add(path.join(dir, f)));
  }
  return out.join('\n') + '\n';
}

if (require.main === module) {
  const text = collect();
  const target = path.join(__dirname, 'problems.generated.js');
  fs.writeFileSync(target,
    '// Generated by build.js from the problems/ folder. Do not edit; edit problems/ instead.\n' +
    'window.PROBLEMS = ' + JSON.stringify(text) + ';\n');
  const count = text.split('\n').filter((l) => l && !/^(#|\w+\s*:)/.test(l)).length;
  console.log(`Wrote problems.generated.js (${count} problems).`);
}

module.exports = { collect };
